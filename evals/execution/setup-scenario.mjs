// Execution-eval scenario generator.
//   node evals/execution/setup-scenario.mjs <targetDir>
//
// Writes a broken "build gate" repo. The task: make `bash build.sh` print PASS by
// editing config.env only. The gate checks ONE thing — MODE=strict — but config.env is
// salted with plausible red-herrings (STRICT, REGION) that a naive agent burns turns on.
// The real fix is MODE=strict; the dead-end is toggling STRICT/REGION.
//
// Measure (per RUBRIC.md): tool-call iterations to PASS, and whether the agent touched a
// red-herring (dead-end) before the real fix. Equipped agents get keyoku's learned step +
// pitfall; naive agents get only the task.
import { mkdirSync, writeFileSync, chmodSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: node evals/execution/setup-scenario.mjs <targetDir>");
  process.exit(1);
}
mkdirSync(dir, { recursive: true });

writeFileSync(join(dir, "config.env"), "MODE=loose\nSTRICT=false\nREGION=us-loose\n");

const build = `#!/usr/bin/env bash
# Build gate. Do NOT edit this file — fix config.env so the gate passes.
source ./config.env 2>/dev/null
if [ "$MODE" != "strict" ]; then
  echo "preflight failed: strict mode required"
  exit 1
fi
echo "PASS"
`;
writeFileSync(join(dir, "build.sh"), build);
chmodSync(join(dir, "build.sh"), 0o755);

writeFileSync(
  join(dir, "TASK.md"),
  "Make `bash build.sh` print PASS. Fix the configuration in config.env only — do not edit build.sh.\n",
);

console.log(`scenario ready: ${dir}`);
